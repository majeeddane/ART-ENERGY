export function emptyHidden(): HiddenData {
  return { work: [], clients: [], team: [], journal: [] };
}

/**
 * Runtime content stored in Postgres / content/runtime.json.
 * `content/site.ts` remains the source of truth for defaults, so new fields
 * added later are filled automatically when old saved data is loaded.
 */
export type SiteData = {
  version: number;
  settings: SiteSettings;
  flags: FeatureFlags;
  content: Record<Locale, Dict>;
  hidden: HiddenData;
  media: MediaItem[];
  updatedAt: string;
};

export function createDefaultSiteData(): SiteData {
  return {
    version: 1,
    settings: {
      ...defaultSettings,
      keywordsAr: [...defaultSettings.keywordsAr],
      keywordsEn: [...defaultSettings.keywordsEn],
      social: { ...defaultSettings.social },
    },
    flags: { ...defaultFlags },
    content: JSON.parse(JSON.stringify({ ar, en })) as Record<Locale, Dict>,
    hidden: emptyHidden(),
    media: [],
    updatedAt: "",
  };
}
